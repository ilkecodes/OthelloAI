def get_brand_profile(client_name: str):
    """Gelişmiş brand profile matching"""
    if not client_name:
        return None
    
    client_lower = client_name.lower().strip()
    
    # 1. Exact match
    for key, profile in BRAND_PROFILES.items():
        if profile["name"].lower() == client_lower:
            print(f"✅ Brand profile found (exact): {profile['name']}")
            return profile
    
    # 2. Aliases match
    for key, profile in BRAND_PROFILES.items():
        for alias in profile.get("aliases", []):
            if alias.lower() in client_lower or client_lower in alias.lower():
                print(f"✅ Brand profile found (alias): {profile['name']}")
                return profile
    
    # 3. Partial match
    for key, profile in BRAND_PROFILES.items():
        name_words = profile["name"].lower().split()
        client_words = client_lower.split()
        
        if any(word in client_words for word in name_words):
            print(f"✅ Brand profile found (partial): {profile['name']}")
            return profile
    
    print(f"⚠️ Brand profile NOT found for: {client_name}")
    return None

def get_all_brand_profiles():
    """Tüm brand profile'ları döndür"""
    return BRAND_PROFILES
